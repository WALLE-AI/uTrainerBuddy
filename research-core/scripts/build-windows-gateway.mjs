import { mkdir, copyFile, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { prepare } from './prepare.mjs';
import { source, root, cache, lock, output, run, hash, cargo, rustEnv, patchesSha256 } from './common.mjs';
import { verifyDashboard, dashboardManifestPath } from './dashboard.mjs';

if(process.platform!=='win32')throw Error('Windows gateway builds require the Windows MSVC build host');
await prepare();
await verifyDashboard();
const dashboardBytes = await readFile(dashboardManifestPath);
await run('python',[resolve(root,'research-core/scripts/verify-source.py'),resolve(cache,'upstream.tar'),source]);
const linux=JSON.parse(await readFile(resolve(output,'manifest.json'),'utf8'));
if(linux.upstream_commit!==lock.commit)throw Error('Build the matching Linux research core first');
const host=await readFile(resolve(output,'orx-host-linux-x86_64'));
if(hash(host)!==linux.files['orx-host-linux-x86_64'].sha256)throw Error('Embedded Linux host digest mismatch');
const destination=resolve(root,'research-core/dist/windows-x86_64');
await mkdir(destination,{recursive:true});
const env={...rustEnv,CARGO_TARGET_DIR:resolve(cache,'target'),CARGO_PROFILE_DEV_DEBUG:'0',CARGO_BUILD_JOBS:'4',ORX_EMBED_HOST_DIR:output};
await run(cargo,['build','--manifest-path',resolve(source,'Cargo.toml'),'--bin','orx','--features','rust-embed/debug-embed','--locked','--target','x86_64-pc-windows-msvc'],{cwd:source,env});
const binary=resolve(cache,'target/x86_64-pc-windows-msvc/debug/orx.exe');
await copyFile(binary,resolve(destination,'orx.exe'));
await copyFile(resolve(source,'LICENSE'),resolve(destination,'LICENSE.OpenResearch'));
await writeFile(resolve(destination,'dashboard.manifest.json'),dashboardBytes);
const bytes=await readFile(binary);
await writeFile(resolve(destination,'manifest.json'),JSON.stringify({upstream_commit:lock.commit,source_archive_sha256:lock.archive.sha256,patches_sha256:patchesSha256,upstream_version:lock.version,target:'x86_64-pc-windows-msvc',profile:'development',ui:'embedded-native-dashboard',files:{'orx.exe':{size:bytes.length,sha256:hash(bytes)},'dashboard.manifest.json':{size:dashboardBytes.length,sha256:hash(dashboardBytes)}}},null,2)+'\n');
console.log('Built native Windows research gateway: '+destination);
