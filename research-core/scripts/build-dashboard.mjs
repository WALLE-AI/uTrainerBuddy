import { mkdir, readFile, stat } from 'node:fs/promises';
import { resolve, dirname, delimiter } from 'node:path';
import { prepare } from './prepare.mjs';
import { source, root, cache, run, rustEnv } from './common.mjs';
import { recordDashboard } from './dashboard.mjs';

await prepare();
await run('python',[resolve(root,'research-core/scripts/verify-source.py'),resolve(cache,'upstream.tar'),source]);
const ui=resolve(source,'ui');
const packageJson=JSON.parse(await readFile(resolve(ui,'package.json'),'utf8'));
const toolVersion=packageJson.packageManager;
if(!/^pnpm@\d+\.\d+\.\d+$/.test(toolVersion))throw Error('Pinned source has an unsupported package manager identity');
const tools=resolve(cache,'ui-tools');
const npmCli=resolve(dirname(process.execPath),'node_modules/npm/bin/npm-cli.js');
await stat(npmCli);
const env={...rustEnv,npm_config_cache:resolve(cache,'npm-cache'),PNPM_HOME:resolve(cache,'pnpm-home'),LOCALAPPDATA:resolve(cache,'node-local'),APPDATA:resolve(cache,'node-roaming'),XDG_CACHE_HOME:resolve(cache,'node-cache'),XDG_DATA_HOME:resolve(cache,'node-data'),PATH:[resolve(tools,'node_modules/.bin'),process.env.PATH].join(delimiter)};
await mkdir(tools,{recursive:true});
await run(process.execPath,[npmCli,'install','--prefix',tools,'--no-save','--ignore-scripts','--no-audit','--no-fund','--registry=https://registry.npmjs.org',toolVersion],{env});
const installedPnpm=JSON.parse(await readFile(resolve(tools,'node_modules/pnpm/package.json'),'utf8'));
if('pnpm@'+installedPnpm.version!==toolVersion)throw Error('Installed pnpm version mismatch');
const nativePackage=resolve(tools,'node_modules/@pnpm/exe.win32-x64');
const nativeInfo=JSON.parse(await readFile(resolve(nativePackage,'package.json'),'utf8'));
if(nativeInfo.version!==installedPnpm.version)throw Error('Native pnpm version mismatch');
const pnpm=resolve(nativePackage,'pnpm.exe');
env.PATH=[nativePackage,env.PATH].join(delimiter);
await run(pnpm,['install','--frozen-lockfile','--ignore-scripts','--registry=https://registry.npmjs.org','--store-dir',resolve(cache,'pnpm-store')],{cwd:ui,env});
await run(pnpm,['run','build'],{cwd:ui,env});
await recordDashboard();
console.log('Built pinned native research dashboard for the transitional desktop research window');
